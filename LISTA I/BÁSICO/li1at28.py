#28 - Concatenar nome e sobrenome em uma única string.
#concatenar significa unir duas ou mais strings em uma única string.
nome = input("Digite o nome: ")
sobrenome = input("Digite o sobrenome: ")
print(f"Nome completo: {nome} {sobrenome}") #exibe o nome completo, que é a concatenação do nome e sobrenome com um espaço entre eles.