#8 - Mostrar o dobro, triplo e raiz quadrada de um número
num = float(input("Digite um número: "))
print(f"Dobro:{num*2}, Triplo: {num*3}, Raíz quadrada: {num**0.5:.2f}")
#a raiz quadrada de um número é calculada elevando o número a 0.5 (ou 1/2).
#elevamos um número com o operador ** (exponenciação) a 0.5 para obter sua raiz quadrada.