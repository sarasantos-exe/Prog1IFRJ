#4 - Converter metros em centímetros
#Para converter metros em centímetros, basta lembrar que 1 metro = 100 centímetros.
#Então, é só multiplicar o valor em metros por 100.
metros = float(input("Digite o valor em metros: "))
centimetros = metros * 100
print("O valor em centímetros é: ", centimetros)